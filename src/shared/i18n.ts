export const messages = { ja, en };

export function createTranslator(locale: Locale) {
  return (key: MessageKey, values: Record<string, string | number> = {}): string =>
    messages[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
      values[name] === undefined ? placeholder : String(values[name]));
}

// Runtime errors and existing feedback can arrive in either supported language.
export function translateMessage(locale: Locale, message: string): string {
  const key = (Object.keys(ja) as MessageKey[]).find((key) => ja[key] === message || en[key] === message);
  return key ? messages[locale][key] : message;
}
